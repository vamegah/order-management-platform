"""Compile a consumer from the published APIs, never from service classes or live schemas."""
import argparse
import importlib.util
import json
from pathlib import Path
import py_compile
import re
import shutil

from graphql import build_schema, parse, validate

ROOT=Path(__file__).resolve().parents[2]
spec=importlib.util.spec_from_file_location("api_contracts",ROOT/"scripts/check_api_contracts.py")
contracts=importlib.util.module_from_spec(spec)
spec.loader.exec_module(contracts)
CLASSES={"product-service":"ProductApi","customer-service":"CustomerApi","order-service":"OrderApi",
         "notification-service":"WebhookApi","payment-service":"PaymentApi","legacy-banking-adapter":"BankingApi"}


def compile_operations(schema,path):
    result={}
    for source in sorted(Path(path).glob("*.graphql")):
        text=source.read_text(encoding="utf-8")
        document=parse(text)
        errors=validate(schema,document)
        if errors: raise ValueError(source.name+": "+"; ".join(error.message for error in errors))
        operations=[item for item in document.definitions if item.kind=="operation_definition"]
        if len(operations)!=1 or operations[0].name is None: raise ValueError("Consumer documents must contain one named operation")
        if operations[0].operation.value not in ('query','mutation'):
            raise ValueError('The public HTTP consumer supports queries and mutations; subscriptions use the separate notification transport')
        name=operations[0].name.value
        if name in result: raise ValueError("Duplicate consumer operation: "+name)
        result[name]=text
    if not result: raise ValueError("No compiled GraphQL consumer operations")
    return result


def generate(root,output,base_root=None):
    root,output=Path(root),Path(output)
    documents={}
    for service,filename in contracts.API_FILES.items():
        document=contracts.load(root/"contracts/openapi/v1"/filename)
        contracts.validate_openapi(document)
        documents[service]=document
    sdl=(root/"contracts/graphql/v1/schema.graphqls").read_text(encoding="utf-8-sig")
    schema=build_schema(sdl)
    operations=compile_operations(schema,root/"clients/public-api/operations")
    if base_root is not None:
        previous=Path(base_root)/"clients/public-api/operations"
        if previous.is_dir(): compile_operations(schema,previous)
    scalars=contracts.load(root/"contracts/graphql/v1/scalars.json")
    output.mkdir(parents=True,exist_ok=True)
    lines=['# Generated by clients/public-api/generate.py; do not edit.',
           'from public_api_runtime import RestClient, GraphQlClient',
           'CONTRACTS = '+repr(documents),'GRAPHQL_SCHEMA = '+repr(sdl),
           'GRAPHQL_OPERATIONS = '+repr(operations),'GRAPHQL_SCALARS = '+repr(scalars)]
    for service,class_name in CLASSES.items():
        lines.extend(['','class '+class_name+'(RestClient):',
            '    def __init__(self, base_url=None, token=None, timeout=20):',
            '        super().__init__(CONTRACTS['+repr(service)+'], base_url, token, timeout)'])
        names=set()
        for operation in contracts.operations(documents[service]).values():
            identifier=operation['operationId']
            name=re.sub(r'(?<!^)(?=[A-Z])','_',identifier).lower().replace('__','_')
            if not re.fullmatch(r'[a-z][a-z0-9_]*',name) or name in names or name in {'call','send'}:
                raise ValueError('Unsafe or conflicting generated method name: '+identifier)
            names.add(name)
            lines.extend(['','    def '+name+'(self, **arguments):','        return self.call('+repr(identifier)+', **arguments)'])
    lines.extend(['','class GraphqlApi(GraphQlClient):',
        '    def __init__(self, base_url, token=None, timeout=20):',
        '        super().__init__(GRAPHQL_SCHEMA, GRAPHQL_OPERATIONS, GRAPHQL_SCALARS, base_url, token, timeout)'])
    generated=output/'api_client.py'
    generated.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    shutil.copyfile(Path(__file__).with_name('runtime.py'),output/'public_api_runtime.py')
    for source in (generated,output/'public_api_runtime.py'): py_compile.compile(str(source),doraise=True)
    return len(documents),len(operations)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root',type=Path,default=ROOT)
    parser.add_argument('--output',type=Path,default=ROOT/'clients/public-api/build')
    parser.add_argument('--base-root',type=Path)
    options=parser.parse_args()
    services,operations=generate(options.root,options.output,options.base_root)
    print(f'Compiled public consumer: {services} REST APIs, {operations} GraphQL operations.')


if __name__=='__main__': main()
