package com.example.omp.order.service;

import com.example.omp.order.clients.dto.CustomerDto;
import com.example.omp.order.domain.*;
import com.example.omp.order.error.OrderNotFoundException;
import com.example.omp.order.repository.OrderRepository;
import com.example.omp.shared.domain.Money;
import java.util.List;
import java.util.UUID;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * Transactional operations on orders. No cross-service calls — all data must be passed in. Called
 * by {@link OrderService} after external lookups.
 */
@Service
public class OrderTransactionService {

    private final OrderRepository orderRepository;
    private final OrderNumberGenerator numberGenerator;
    private final com.example.omp.order.events.OrderEventPublisher events;
    private final CheckoutJournal journal;

    public OrderTransactionService(
            OrderRepository orderRepository,
            OrderNumberGenerator numberGenerator,
            com.example.omp.order.events.OrderEventPublisher events,
            CheckoutJournal journal) {
        this.orderRepository = orderRepository;
        this.numberGenerator = numberGenerator;
        this.events = events;
        this.journal = journal;
    }

    /**
     * Creates and persists an order from pre-fetched customer and product data.
     *
     * <p><b>This method performs NO external calls.</b> All data comes from the caller. The
     * transaction is short — no network I/O, no cross-service coordination. This is the whole point
     * of splitting this method out of {@code OrderService}: the transactional core is isolated from
     * the orchestration logic.
     *
     * <p><b>Inputs:</b>
     *
     * <ul>
     *   <li>{@code orderId} — pre-generated by the caller. Used as the primary key. Also used
     *       (transitively) as part of downstream idempotency keys, so it must be stable across
     *       retries of the same logical operation.
     *   <li>{@code customer} — the customer DTO from customer-service. The email is snapshotted
     *       onto the order (so the order is not affected if the customer later changes their
     *       email).
     *   <li>{@code shippingAddress} — the shipping address for this order. Snapshotted (not
     *       referenced) so later changes to the customer's address don't affect existing orders.
     *   <li>{@code drafts} — the order lines. Each draft is a product snapshot (ID, SKU, name, unit
     *       price) plus a quantity.
     *   <li>{@code paymentId} — the payment intent ID from payment-service. Stored on the order so
     *       it can be referenced during confirm/refund.
     * </ul>
     *
     * <p><b>Output:</b> the saved order. Its ID is the passed-in {@code orderId}; its {@code
     * orderNumber} is generated from the database sequence; its {@code createdAt}, {@code
     * updatedAt}, and line items are all populated.
     *
     * <p><b>Transaction scope:</b> annotated {@code @Transactional}. The whole method runs in a
     * single transaction — the order, its lines, and the initial status history entry are all
     * committed atomically. If any insert fails (e.g., duplicate order number), nothing is
     * persisted.
     *
     * <p><b>Retry safety:</b> if this method is retried (e.g., because the caller's transaction
     * boundary retries), the pre-generated {@code orderId} means the retry will fail on the primary
     * key unique constraint rather than creating a duplicate. Callers should treat a duplicate-key
     * failure as "the previous attempt actually succeeded."
     */
    @Transactional
    public Order create(
            UUID orderId,
            CustomerDto customer,
            ShippingAddress shippingAddress,
            List<OrderLineDraft> drafts,
            UUID paymentId,
            List<UUID> reservationIds) {
        if (reservationIds.size() != drafts.size()) {
            throw new IllegalArgumentException("Every order line requires a reservation");
        }

        // -------------------------------------------------------------------------
        // Generate the human-readable order number.
        // -------------------------------------------------------------------------
        // The order number comes from a database sequence (orders.order_number_seq).
        // The generator queries nextval() and formats as ORD-YYYY-NNNNNNN. The
        // sequence is per-database, so uniqueness is guaranteed even under
        // concurrent order creation.
        // -------------------------------------------------------------------------
        journal.accept(orderId);
        OrderNumber orderNumber = numberGenerator.next();

        // -------------------------------------------------------------------------
        // Construct the Order aggregate.
        // -------------------------------------------------------------------------
        // The Order constructor initializes status to DRAFT, sets totals to zero,
        // and appends an initial "created" entry to the status history. The
        // customer email is snapshotted here — this is the value the order will
        // report forever, regardless of later changes to the customer record.
        // -------------------------------------------------------------------------
        Order order =
                new Order(
                        orderId,
                        orderNumber,
                        customer.id(),
                        customer.email(),
                        drafts.get(0).unitPrice().getCurrencyCode(), // currency from first line
                        shippingAddress,
                        paymentId);

        // -------------------------------------------------------------------------
        // Add line items.
        // -------------------------------------------------------------------------
        // Each draft becomes an OrderLine entity. The line snapshots the product
        // details — SKU, name, unit price — at the moment of order creation.
        // Later changes to the product in product-service don't affect these
        // lines. The OrderLine constructor computes lineTotal = unitPrice × qty.
        //
        // Note: adding lines to the order triggers recalculation of subtotal and
        // total (see Order.addLine → recalculateTotals). So after this loop, the
        // order's subtotal and total are correct.
        // -------------------------------------------------------------------------
        for (int index = 0; index < drafts.size(); index++) {
            OrderLineDraft draft = drafts.get(index);
            OrderLine line =
                    new OrderLine(
                            draft.productId(),
                            draft.sku(),
                            draft.name(),
                            draft.unitPrice(),
                            draft.quantity());
            line.setReservationId(reservationIds.get(index));
            order.addLine(line);
        }

        // -------------------------------------------------------------------------
        // Persist.
        // -------------------------------------------------------------------------
        // saveAndFlush forces the INSERT immediately rather than deferring to
        // transaction commit. This surfaces any constraint violation (e.g., a
        // duplicate order number, or a duplicate order ID from a bad retry)
        // inside this method, where the caller can handle it, rather than at
        // commit time outside the caller's try/catch.
        //
        // Cascade rules on Order.lines and Order.statusHistory mean the lines
        // and history entry are persisted automatically when the order is saved.
        // -------------------------------------------------------------------------
        Order saved = orderRepository.saveAndFlush(order);
        events.publishCreated(saved);

        return saved;
    }

    @Transactional
    public Order findAndApply(UUID id, java.util.function.Consumer<Order> mutation) {
        Order order =
                orderRepository
                        .findByIdWithFullDetails(id)
                        .orElseThrow(() -> new OrderNotFoundException(id));
        mutation.accept(order);
        return order;
    }

    @Transactional(readOnly = true)
    public Order findByIdFull(UUID id) {
        Order order =
                orderRepository
                        .findByIdWithFullDetails(id)
                        .orElseThrow(() -> new OrderNotFoundException(id));
        order.getStatusHistory().size();
        return order;
    }

    /** Internal carrier for a line before the entity is created. */
    public record OrderLineDraft(
            UUID productId, String sku, String name, Money unitPrice, int quantity) {}
}
